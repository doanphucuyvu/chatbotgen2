  function springProgress(t, distance, limit = 7) {
    if (t >= 1) return 1;
    // Adapt damping to travel distance instead of clipping the overshoot;
    // clipping would create a flat spot at the turning point.
    const frequency = Math.min(6.5, 8 * Math.PI / Math.log(Math.max(48, distance / limit)));
    return 1 - Math.exp(-8 * t) * (Math.cos(frequency * t) + 8 / frequency * Math.sin(frequency * t));
  }
  function flightStep(now) {
    flightFrame = 0;
    // Read all destinations before any writes. The placeholder follows actual
    // scrolling, panel depth, keyboard movement and incoming reply growth.
    const viewport = chat.getBoundingClientRect();
    const plans = [...flights.values()].map(flight => ({flight, rect: flight.slot.getBoundingClientRect()}));
    for (const {flight, rect} of plans) {
      if (!flight.message.isConnected || document.hidden) { flight.finish(); continue; }
      const elapsed = Math.max(0, now - flight.start);
      const t = Math.min(1, elapsed / flight.travelDuration);
      const tx = rect.left + rect.width / 2;
      // A forced scroll may start many screens away from the new row. Aim
      // inside the conversation until that row enters it, never off-screen.
      const ty = Math.max(viewport.top + rect.height / 2 + 4, Math.min(viewport.bottom - rect.height / 2 - 4, rect.top + rect.height / 2));
      const dx = tx - flight.x, dy = ty - flight.y, distance = Math.hypot(dx, dy);
      const p = springProgress(t, distance), nx = distance ? dx / distance : 0, ny = distance ? dy / distance : 0;
      const stretch = Math.sin(Math.PI * Math.min(1, p)) * .042;
      const base = .94 + .06 * Math.min(1, t / .3);
      const sx = rect.width / flight.width, sy = rect.height / flight.height;
      // One continuous transform owns both travel and the soft touchdown.
      // The contact pulse and its small rebound start and end at rest.
      const contactStart = flight.travelDuration * .78;
      const q = Math.min(1, Math.max(0, (elapsed - contactStart) / (flight.duration - contactStart)));
      const contact = Math.sin(2 * Math.PI * q) * Math.sin(Math.PI * q) ** 2 * Math.exp(-1.6 * q);
      const a = (base + stretch * nx * nx - stretch * .35 * ny * ny) * sx * (1 + contact * .05);
      const b = stretch * 1.35 * nx * ny;
      const d = (base + stretch * ny * ny - stretch * .35 * nx * nx) * sy * (1 - contact * .08);
      const x = flight.x + dx * p - flight.width / 2, y = flight.y + dy * p - flight.height / 2;
      flight.content.style.transform = `translate3d(${x.toFixed(3)}px,${y.toFixed(3)}px,0) matrix(${a.toFixed(5)},${b.toFixed(5)},${b.toFixed(5)},${d.toFixed(5)},0,0)`;
      if (elapsed >= flight.duration) flight.finish();
    }
    if (flights.size) flightFrame = requestAnimationFrame(flightStep);
  }
