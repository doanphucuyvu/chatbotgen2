  function findAnswer(question) {
    const qLower = question.toLowerCase();
    for (const [key, value] of Object.entries(faqData)) {
      if (qLower.includes(key.toLowerCase())) return value;
    }
    const keywords = {
      'giới thiệu': 'Giới thiệu chung về CLB SMY',
      'liên hệ': 'Thông tin liên hệ',
      'tham gia': 'Cách tham gia CLB SMY',
      'đăng ký': 'Đăng ký làm Hội viên',
      'sứ mệnh': 'Sứ mệnh',
      'tầm nhìn': 'Tầm nhìn',
      'ban điều hành': 'Ban điều hành',
      'phân ban': 'Các phân ban',
      'thành viên': 'Thành viên trong từng ban',
      'quy chế': 'Quy chế hoạt động CLB',
      'tài chính': 'Tài chính',
      'khen thưởng': 'Khen thưởng',
      'kỷ luật': 'Kỷ luật'
    };
    let best = { key: null, score: 0 };
    for (const [kw, ansKey] of Object.entries(keywords)) {
      if (qLower.includes(kw)) {
        const score = kw.length * (qLower.split(kw).length - 1);
        if (score > best.score) best = { key: ansKey, score };
      }
    }
    return best.score >= 3 ? faqData[best.key] : null;
  }

