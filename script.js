        const decay = Math.exp(-halfDamping * elapsed);
        const sine = Math.sin(frequency * elapsed), cosine = Math.cos(frequency * elapsed);
        const delta = state.values[i] - state.target[i], velocity = state.velocity[i];
        state.values[i] = state.target[i] + decay * (delta * cosine + (velocity + halfDamping * delta) / frequency * sine);
        state.velocity[i] = decay * (velocity * cosine - (halfDamping * velocity + stiffness * delta) / frequency * sine);
